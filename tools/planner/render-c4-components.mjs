#!/usr/bin/env node
/**
 * ReconcileAI — C4 Level 3 (Components) renderer.
 *
 * Reads model/*.ts DIRECTLY, every run. It does not read the committed
 * docs/model-graph.json produced by tools/planner/extract.mjs — a cached
 * derived artifact can go stale relative to the tree without anything
 * catching it (see docs/HANDOFF.md on extractor/tree divergence). This
 * script re-derives from source every time it runs, so "freshness" means
 * "matches model/*.ts right now," not "matches whatever was last extracted."
 *
 * Deterministic by construction: no `Date.now()`, no git commit hash, no
 * generation timestamp anywhere in the output. Two runs against an
 * unchanged tree produce byte-identical text. This matters because
 * tools/check-c4-freshness.mjs diffs this output against a committed file,
 * and tools/githooks/post-commit re-runs it after every commit — either one
 * would misfire on non-deterministic output (see both files' headers).
 *
 * A module whose entire file carries the literal banner
 * "WHOLE MODULE IS `@dropped-for-v1`" (model/presentation.ts,
 * model/deployment.ts today) is rendered in a visually distinct class and
 * labelled DROPPED. Silently drawing a dropped-for-v1 module as a live
 * component is the specific failure this repository has already recorded
 * against its other hand-drawn HTML visuals (docs/INDEX.md).
 *
 * Usage:
 *   node tools/planner/render-c4-components.mjs            # print to stdout
 *   node tools/planner/render-c4-components.mjs --write     # write docs/c4-components.mmd
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, '..', '..')
const MODEL_DIR = path.join(REPO_ROOT, 'model')
const OUT_PATH = path.join(REPO_ROOT, 'docs', 'c4-components.mmd')

const DROPPED_BANNER = 'WHOLE MODULE IS `@dropped-for-v1`'
const IMPORT_RE = /from\s+['"]\.\/([a-zA-Z0-9_-]+)(?:\.ts)?['"]/g

/** Re-derive the module import graph straight from model/*.ts. Pure function of the tree. */
export function buildGraph() {
  const files = readdirSync(MODEL_DIR)
    .filter((f) => f.endsWith('.ts'))
    .map((f) => f.slice(0, -3))
    .sort()

  const modules = files.map((name) => {
    const src = readFileSync(path.join(MODEL_DIR, `${name}.ts`), 'utf8')
    const dropped = src.includes(DROPPED_BANNER)
    const imports = new Set()
    for (const m of src.matchAll(IMPORT_RE)) {
      if (m[1] !== name) imports.add(m[1])
    }
    return { name, dropped, imports: [...imports].sort() }
  })

  const edgeCount = modules.reduce((n, m) => n + m.imports.length, 0)
  const droppedCount = modules.filter((m) => m.dropped).length

  return { modules, edgeCount, droppedCount, moduleCount: modules.length }
}

/** Render the graph as deterministic Mermaid flowchart text. No timestamps, no hashes. */
export function renderMermaid(graph) {
  const lines = []
  lines.push('%% AUTO-GENERATED by tools/planner/render-c4-components.mjs — do not hand-edit.')
  lines.push('%% Regenerate: node tools/planner/render-c4-components.mjs --write')
  lines.push('flowchart TB')
  lines.push('  classDef live fill:#DCE8EF,stroke:#1D5C8A,color:#123A55;')
  lines.push('  classDef dropped fill:#F3DEDB,stroke:#A3312A,color:#4A1B0C,stroke-dasharray: 4 3;')
  lines.push('')

  for (const m of graph.modules) {
    const label = m.dropped ? `${m.name}.ts fa:DROPPED-FOR-V1` : `${m.name}.ts`
    lines.push(`  ${m.name}["${label}"]:::${m.dropped ? 'dropped' : 'live'}`)
  }
  lines.push('')
  for (const m of graph.modules) {
    for (const target of m.imports) {
      lines.push(`  ${m.name} --> ${target}`)
    }
  }

  lines.push('')
  lines.push(
    `%% scope: ${graph.moduleCount} modules, ${graph.edgeCount} import edges, ` +
      `${graph.droppedCount} flagged dropped-for-v1`,
  )
  return lines.join('\n') + '\n'
}

function main() {
  const graph = buildGraph()
  const text = renderMermaid(graph)
  if (process.argv.includes('--write')) {
    writeFileSync(OUT_PATH, text)
    console.log(
      `wrote ${path.relative(REPO_ROOT, OUT_PATH)} — ${graph.moduleCount} modules, ` +
        `${graph.edgeCount} edges, ${graph.droppedCount} dropped-for-v1`,
    )
  } else {
    process.stdout.write(text)
  }
}

// See extract-c4-data.mjs: the `file://${process.argv[1]}` form silently no-ops
// with exit 0 on any path containing a space.
const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (invokedDirectly) main()
