/**
 * A MINIMAL POSTGRESQL WIRE CLIENT — G3921, 4 Oct 2026.
 *
 * 🛑 WHY THIS FILE EXISTS INSTEAD OF `pg`. Every Lambda under `infra/lambda/`
 * is a ZERO-DEPENDENCY directory asset (`storage-stack.ts`: *"no bundler, no
 * network"*), and `infra/package.json` carries no driver — G259 keeps that
 * manifest to the CDK alone, and the root manifest's `pg` is the serving
 * container's. The rotation function needs exactly four things from a
 * PostgreSQL server: a TLS upgrade, SCRAM-SHA-256 (or MD5) authentication, a
 * simple-protocol query, and an orderly close. That is what is here, and
 * nothing else: no extended protocol, no bind parameters, no COPY, no pool.
 *
 * ⚠️ THE QUERY PATH TAKES NO PARAMETERS, AND THAT IS SAFE ONLY BECAUSE OF WHAT
 * IS SENT THROUGH IT. `ALTER ROLE` is utility syntax and takes no bind
 * parameters at any price (`db/provision.ts#setRolePassword` says the same),
 * so the caller interpolates — and `rotation.mjs` interpolates only an
 * identifier matched against `ROLE_NAME_PATTERN` and a SCRAM verifier matched
 * against `VERIFIER_PATTERN`. Neither can carry a quote.
 *
 * 🛑 TLS FAILS CLOSED. A non-loopback host is upgraded with SSLRequest and the
 * server certificate is VERIFIED (`rejectUnauthorized: true`, against the
 * runtime's RDS bundle — see `NODE_EXTRA_CA_CERTS` on the function). A server
 * that answers `N` to SSLRequest is refused rather than spoken to in plaintext.
 * That is STRONGER than `db/env.ts#dbSsl`, which encrypts and does not verify;
 * the reason is that this function sends the cluster ADMIN's password, and the
 * serving process's passwords are not that.
 */

import net from 'node:net'
import tls from 'node:tls'
import { createHash, createHmac, pbkdf2Sync, randomBytes, timingSafeEqual } from 'node:crypto'

const PROTOCOL_V3 = 196608
const SSL_REQUEST_CODE = 80877103
const CONNECT_TIMEOUT_MS = 10_000

/** A server-reported error. `code` is the SQLSTATE; `fields` is the raw set. */
export class PgServerError extends Error {
  /** @param {Record<string, string>} fields */
  constructor(fields) {
    super(`${fields.S ?? 'ERROR'} ${fields.C ?? '?????'}: ${fields.M ?? 'no message'}`)
    this.name = 'PgServerError'
    this.code = fields.C
    this.fields = fields
  }
}

/** A protocol or authentication failure on OUR side of the wire. */
export class PgClientError extends Error {
  /** @param {string} reason */
  constructor(reason) {
    super(reason)
    this.name = 'PgClientError'
    this.reason = reason
  }
}

/** A loopback host is the disposable local database and takes no TLS — `db/env.ts`'s rule. */
export function isLoopback(host) {
  return host === '127.0.0.1' || host === 'localhost' || host === '::1'
}

// ------------------------------------------------------------------- SCRAM

const hmac = (key, data) => createHmac('sha256', key).update(data).digest()
const sha256 = (data) => createHash('sha256').update(data).digest()

function xor(a, b) {
  const out = Buffer.alloc(a.length)
  for (let i = 0; i < a.length; i += 1) out[i] = a[i] ^ b[i]
  return out
}

/**
 * The SCRAM-SHA-256 client computation, separated from the socket so that
 * RFC 7677's own test vector can witness it (`tests/infra/role-secret-rotation.test.mjs`).
 *
 * ⚠️ NO SASLprep. Every password this function ever handles is generated by
 * Secrets Manager from printable ASCII with `PASSWORD_EXCLUDED_CHARACTERS`
 * removed, and SASLprep is the identity on printable ASCII. A password outside
 * that set is refused before it reaches here (`rotation.mjs`).
 *
 * @param {{password: string, clientFirstBare: string, serverFirst: string}} args
 * @returns {{clientFinal: string, expectedServerSignature: Buffer}}
 */
export function scramClientFinal({ password, clientFirstBare, serverFirst }) {
  const attrs = Object.fromEntries(
    serverFirst.split(',').map((kv) => [kv.slice(0, 1), kv.slice(2)]),
  )
  const clientNonce = clientFirstBare.split(',').find((p) => p.startsWith('r='))?.slice(2)
  if (attrs.r === undefined || clientNonce === undefined || !attrs.r.startsWith(clientNonce)) {
    throw new PgClientError('scram_nonce_mismatch')
  }
  if (attrs.s === undefined || attrs.i === undefined) throw new PgClientError('scram_server_first_malformed')
  const iterations = Number(attrs.i)
  if (!Number.isInteger(iterations) || iterations < 4096) {
    throw new PgClientError('scram_iterations_refused')
  }
  const salted = pbkdf2Sync(password, Buffer.from(attrs.s, 'base64'), iterations, 32, 'sha256')
  const clientKey = hmac(salted, 'Client Key')
  const storedKey = sha256(clientKey)
  const withoutProof = `c=biws,r=${attrs.r}`
  const authMessage = `${clientFirstBare},${serverFirst},${withoutProof}`
  const proof = xor(clientKey, hmac(storedKey, authMessage))
  const expectedServerSignature = hmac(hmac(salted, 'Server Key'), authMessage)
  return { clientFinal: `${withoutProof},p=${proof.toString('base64')}`, expectedServerSignature }
}

/**
 * A SCRAM-SHA-256 VERIFIER in PostgreSQL's stored format —
 * `SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>`.
 *
 * 🛑 THIS IS WHAT `ALTER ROLE … PASSWORD` RECEIVES, NEVER THE PASSWORD. Two
 * reasons, and the second is the deciding one: (1) PostgreSQL stores a
 * pre-hashed verifier as given, so the plaintext never crosses the wire; (2)
 * `PG_LOG_CONTAINMENT_PARAMETERS` sets `log_min_error_statement = error`, so a
 * FAILED `ALTER ROLE` is written into the cluster's PostgreSQL log — which
 * `Data` exports to CloudWatch. A failed plaintext statement would put a live
 * credential in a log group. A verifier there gives an attacker an offline
 * guessing target against a 40-character random password, and no login.
 *
 * @param {string} password
 * @param {{salt?: Buffer, iterations?: number}} [options]
 */
export function scramVerifier(password, { salt = randomBytes(16), iterations = 4096 } = {}) {
  const salted = pbkdf2Sync(password, salt, iterations, 32, 'sha256')
  const storedKey = sha256(hmac(salted, 'Client Key'))
  const serverKey = hmac(salted, 'Server Key')
  return `SCRAM-SHA-256$${iterations}:${salt.toString('base64')}$${storedKey.toString('base64')}:${serverKey.toString('base64')}`
}

/** Does `verifier` (PostgreSQL's stored format) accept `password`? */
export function verifierAccepts(verifier, password) {
  const m = /^SCRAM-SHA-256\$(\d+):([A-Za-z0-9+/=]+)\$([A-Za-z0-9+/=]+):([A-Za-z0-9+/=]+)$/.exec(verifier)
  if (m === null) return false
  const recomputed = scramVerifier(password, {
    salt: Buffer.from(m[2], 'base64'),
    iterations: Number(m[1]),
  })
  const a = Buffer.from(recomputed)
  const b = Buffer.from(verifier)
  return a.length === b.length && timingSafeEqual(a, b)
}

// --------------------------------------------------------------- framing

function frame(type, body) {
  const len = Buffer.alloc(4)
  len.writeInt32BE(body.length + 4)
  return type === null ? Buffer.concat([len, body]) : Buffer.concat([Buffer.from(type), len, body])
}

const cstr = (s) => Buffer.from(`${s}\0`, 'utf8')

function parseErrorFields(body) {
  const fields = {}
  let i = 0
  while (i < body.length && body[i] !== 0) {
    const key = String.fromCharCode(body[i])
    const end = body.indexOf(0, i + 1)
    fields[key] = body.subarray(i + 1, end).toString('utf8')
    i = end + 1
  }
  return fields
}

/**
 * A message reader over a socket. `next()` resolves to `{type, body}`; a socket
 * error or close rejects every pending and future read.
 */
function messageReader(socket) {
  let buffer = Buffer.alloc(0)
  const waiting = []
  let failure = null
  const pump = () => {
    while (waiting.length > 0) {
      if (failure !== null) {
        waiting.shift().reject(failure)
        continue
      }
      if (buffer.length < 5) return
      const length = buffer.readInt32BE(1)
      if (buffer.length < length + 1) return
      const type = String.fromCharCode(buffer[0])
      const body = buffer.subarray(5, length + 1)
      buffer = buffer.subarray(length + 1)
      waiting.shift().resolve({ type, body })
    }
  }
  socket.on('data', (chunk) => {
    buffer = Buffer.concat([buffer, chunk])
    pump()
  })
  const fail = (err) => {
    failure = failure ?? err
    pump()
  }
  socket.on('error', (err) => fail(err))
  socket.on('close', () => fail(new PgClientError('connection_closed')))
  return {
    next: () =>
      new Promise((resolve, reject) => {
        waiting.push({ resolve, reject })
        pump()
      }),
  }
}

function connectSocket(host, port) {
  return new Promise((resolve, reject) => {
    const socket = net.connect({ host, port })
    socket.setTimeout(CONNECT_TIMEOUT_MS, () => {
      socket.destroy(new PgClientError('connect_timeout'))
    })
    socket.once('connect', () => resolve(socket))
    socket.once('error', reject)
  })
}

function readOneByte(socket) {
  return new Promise((resolve, reject) => {
    socket.once('data', (chunk) => resolve(chunk.subarray(0, 1).toString()))
    socket.once('error', reject)
  })
}

async function upgradeToTls(socket, host) {
  const req = Buffer.alloc(8)
  req.writeInt32BE(8, 0)
  req.writeInt32BE(SSL_REQUEST_CODE, 4)
  socket.write(req)
  const answer = await readOneByte(socket)
  if (answer !== 'S') {
    socket.destroy()
    throw new PgClientError('server_refused_tls')
  }
  return new Promise((resolve, reject) => {
    const secure = tls.connect({ socket, servername: host, rejectUnauthorized: true }, () =>
      resolve(secure),
    )
    secure.once('error', reject)
  })
}

/**
 * Connect and authenticate. Resolves to `{ query(sql), end() }`.
 *
 * @param {{host: string, port: number, user: string, password: string, database: string, tls?: boolean}} options
 *   `tls` defaults to "not loopback" and may only be turned OFF for a loopback host.
 */
export async function connect({ host, port, user, password, database, tls: useTls }) {
  const wantTls = useTls ?? !isLoopback(host)
  if (!wantTls && !isLoopback(host)) throw new PgClientError('plaintext_refused_off_loopback')

  let socket = await connectSocket(host, port)
  socket.setTimeout(0)
  if (wantTls) socket = await upgradeToTls(socket, host)
  const reader = messageReader(socket)
  const send = (buf) => socket.write(buf)

  const startupBody = Buffer.alloc(4)
  startupBody.writeInt32BE(PROTOCOL_V3)
  send(
    frame(
      null,
      Buffer.concat([
        startupBody,
        cstr('user'),
        cstr(user),
        cstr('database'),
        cstr(database),
        cstr('application_name'),
        cstr('reconcile-role-rotation'),
        Buffer.from([0]),
      ]),
    ),
  )

  let clientFirstBare = null
  let expectedServerSignature = null
  for (;;) {
    const { type, body } = await reader.next()
    if (type === 'E') {
      socket.destroy()
      throw new PgServerError(parseErrorFields(body))
    }
    if (type !== 'R') continue
    const code = body.readInt32BE(0)
    if (code === 0) break
    if (code === 5) {
      // MD5: md5(md5(password + user) + salt), hex, prefixed.
      const salt = body.subarray(4, 8)
      const inner = createHash('md5').update(password + user).digest('hex')
      const outer = createHash('md5').update(Buffer.concat([Buffer.from(inner), salt])).digest('hex')
      send(frame('p', cstr(`md5${outer}`)))
      continue
    }
    if (code === 10) {
      const mechanisms = body.subarray(4).toString('utf8').split('\0').filter(Boolean)
      if (!mechanisms.includes('SCRAM-SHA-256')) {
        socket.destroy()
        throw new PgClientError('scram_sha_256_not_offered')
      }
      clientFirstBare = `n=,r=${randomBytes(18).toString('base64')}`
      const initial = Buffer.from(`n,,${clientFirstBare}`)
      const len = Buffer.alloc(4)
      len.writeInt32BE(initial.length)
      send(frame('p', Buffer.concat([cstr('SCRAM-SHA-256'), len, initial])))
      continue
    }
    if (code === 11) {
      if (clientFirstBare === null) throw new PgClientError('scram_out_of_order')
      const computed = scramClientFinal({
        password,
        clientFirstBare,
        serverFirst: body.subarray(4).toString('utf8'),
      })
      expectedServerSignature = computed.expectedServerSignature
      send(frame('p', Buffer.from(computed.clientFinal)))
      continue
    }
    if (code === 12) {
      const v = body.subarray(4).toString('utf8')
      const signature = v.startsWith('v=') ? Buffer.from(v.slice(2), 'base64') : Buffer.alloc(0)
      if (
        expectedServerSignature === null ||
        signature.length !== expectedServerSignature.length ||
        !timingSafeEqual(signature, expectedServerSignature)
      ) {
        socket.destroy()
        throw new PgClientError('scram_server_signature_mismatch')
      }
      continue
    }
    // Cleartext (3) and every other method: refused. Nothing here needs them.
    socket.destroy()
    throw new PgClientError(`auth_method_refused_${code}`)
  }

  // Drain ParameterStatus / BackendKeyData until ReadyForQuery.
  for (;;) {
    const { type, body } = await reader.next()
    if (type === 'E') {
      socket.destroy()
      throw new PgServerError(parseErrorFields(body))
    }
    if (type === 'Z') break
  }

  return {
    /**
     * Simple-protocol query. Resolves to `{ fields, rows }` (rows of text|null),
     * or rejects with the server's error after the connection is ready again.
     * @param {string} sql
     */
    async query(sql) {
      send(frame('Q', cstr(sql)))
      let fields = []
      const rows = []
      let error = null
      for (;;) {
        const { type, body } = await reader.next()
        if (type === 'T') {
          const count = body.readInt16BE(0)
          fields = []
          let i = 2
          for (let f = 0; f < count; f += 1) {
            const end = body.indexOf(0, i)
            fields.push(body.subarray(i, end).toString('utf8'))
            i = end + 1 + 18
          }
        } else if (type === 'D') {
          const count = body.readInt16BE(0)
          const row = []
          let i = 2
          for (let c = 0; c < count; c += 1) {
            const len = body.readInt32BE(i)
            i += 4
            if (len === -1) row.push(null)
            else {
              row.push(body.subarray(i, i + len).toString('utf8'))
              i += len
            }
          }
          rows.push(row)
        } else if (type === 'E') {
          error = new PgServerError(parseErrorFields(body))
        } else if (type === 'Z') {
          break
        }
      }
      if (error !== null) throw error
      return { fields, rows }
    },
    async end() {
      try {
        send(frame('X', Buffer.alloc(0)))
      } finally {
        socket.end()
      }
    },
  }
}
