/**
 * THE STAGING MOCK OIDC IDP — THE LAMBDA ENTRY POINT (G2996–G3002).
 *
 * 🛑 READ `infra/lib/mock-idp-stack.ts`, THEN `idp.mjs`. This file is the
 * wiring and holds no decision: it reads its environment, refuses to run
 * outside staging, and hands `idp.mjs` the functions that reach AWS.
 *
 *   ⛔ THE SIGNING KEY IS NOT HERE AND IS NOT ANYWHERE IN THIS REPOSITORY. It
 *      is an asymmetric KMS key (`RSA_2048`, `SIGN_VERIFY`) minted by
 *      CloudFormation at deploy; this function holds `kms:Sign` and
 *      `kms:GetPublicKey` on THAT key and nothing else, so the private half
 *      never exists outside KMS.
 *   ⛔ THE PASSWORD IS NOT HERE. It is one Secrets Manager secret the stack
 *      creates with an EMPTY `password` field; until a person puts a value the
 *      door refuses every sign-in (`password_not_set`).
 *   ⛔ THE CLIENT SECRET COGNITO PRESENTS IS NOT HERE. It is generated by
 *      Secrets Manager at deploy and dynamic-referenced into the three Cognito
 *      providers; this function reads it at run time to check them.
 *
 * ⚠️ THE AWS SDK IS IMPORTED DYNAMICALLY, FOR `tenant-key-minter/index.mjs`'s
 * REASON: `@aws-sdk/*` ships with `nodejs22.x` and is on disk nowhere in this
 * repository's manifests, so a static import would make this module
 * unloadable by its own suite.
 */

import { createHash, createPublicKey } from 'node:crypto'

import { allowedRedirectOrigin, handle, MOCK_IDP_ENVIRONMENT, parseCatalogue } from './idp.mjs'

const SECRET_CACHE_MS = 60_000

function required(env, name) {
  const v = env[name]
  if (typeof v !== 'string' || v === '') throw new Error(`mock-idp: ${name} is not set`)
  return v
}

/** Build everything `idp.mjs` takes. Exported for the suite, which passes fakes for the two clients. */
export function awsDeps({ kms, secrets, commands, env, now = () => Date.now() }) {
  /* FENCE 1, AT RUN TIME (G2997). The stack refuses to synthesise outside
   * staging; this refuses to SERVE outside it, so a copied function is inert. */
  if (env.MOCK_IDP_ENVIRONMENT !== MOCK_IDP_ENVIRONMENT) {
    throw new Error(
      `mock-idp: refusing to run in environment '${String(env.MOCK_IDP_ENVIRONMENT)}'. ` +
        'This door exists on staging alone and the stack refuses to synthesise it anywhere else.',
    )
  }
  const keyId = required(env, 'MOCK_IDP_KMS_KEY_ID')
  const passwordSecret = required(env, 'MOCK_IDP_PASSWORD_SECRET')
  const clientSecretName = required(env, 'MOCK_IDP_CLIENT_SECRET')
  const allowedRedirectUri = required(env, 'MOCK_IDP_ALLOWED_REDIRECT_URI')
  /* G3282/G3284: the sign-in hand-off navigates a browser to this value, so
   * one that is not an absolute https URL refuses to START rather than
   * serving a 500 — or a plain-text redirect — on the first sign-in. */
  allowedRedirectOrigin(allowedRedirectUri)
  const catalogue = parseCatalogue(required(env, 'MOCK_IDP_CATALOGUE'))

  const cache = new Map()
  async function secretJson(name) {
    const hit = cache.get(name)
    if (hit !== undefined && now() - hit.at < SECRET_CACHE_MS) return hit.value
    const out = await secrets.send(new commands.GetSecretValueCommand({ SecretId: name }))
    let value = {}
    try {
      value = JSON.parse(typeof out.SecretString === 'string' ? out.SecretString : '{}')
    } catch {
      value = {}
    }
    cache.set(name, { at: now(), value })
    return value
  }

  let jwk = null
  return {
    catalogue,
    now,
    allowedRedirectUri,
    log: (line) => console.log(JSON.stringify(line)),
    password: async () => {
      const v = (await secretJson(passwordSecret)).password
      return typeof v === 'string' ? v : ''
    },
    clientSecret: async () => {
      const v = (await secretJson(clientSecretName)).clientSecret
      if (typeof v !== 'string' || v === '') throw new Error('mock-idp: the client secret is empty')
      return v
    },
    publicJwk: async () => {
      if (jwk !== null) return jwk
      const out = await kms.send(new commands.GetPublicKeyCommand({ KeyId: keyId }))
      const der = Buffer.from(out.PublicKey)
      const exported = createPublicKey({ key: der, format: 'der', type: 'spki' }).export({ format: 'jwk' })
      jwk = {
        kty: 'RSA',
        use: 'sig',
        alg: 'RS256',
        kid: createHash('sha256').update(der).digest('base64url').slice(0, 16),
        n: exported.n,
        e: exported.e,
      }
      return jwk
    },
    signRs256: async (bytes) => {
      const out = await kms.send(
        new commands.SignCommand({
          KeyId: keyId,
          Message: bytes,
          MessageType: 'RAW',
          SigningAlgorithm: 'RSASSA_PKCS1_V1_5_SHA_256',
        }),
      )
      return Buffer.from(out.Signature).toString('base64url')
    },
  }
}

let deps = null

export async function handler(event) {
  if (deps === null) {
    const kmsSdk = await import('@aws-sdk/client-kms')
    const smSdk = await import('@aws-sdk/client-secrets-manager')
    deps = awsDeps({
      kms: new kmsSdk.KMSClient({}),
      secrets: new smSdk.SecretsManagerClient({}),
      commands: {
        GetPublicKeyCommand: kmsSdk.GetPublicKeyCommand,
        SignCommand: kmsSdk.SignCommand,
        GetSecretValueCommand: smSdk.GetSecretValueCommand,
      },
      env: process.env,
    })
  }
  return handle(event, deps)
}
