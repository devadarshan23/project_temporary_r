import { ExceptionRegister } from './components/ExceptionRegister.tsx'
import {
  ILLUSTRATIVE_EXCEPTIONS,
  ILLUSTRATIVE_LANES,
  ILLUSTRATIVE_PROVENANCE,
  ILLUSTRATIVE_RUNS,
} from './illustrative.ts'

/** `frontend/dist-ssr` at run time — derived from this file, never from cwd. */
const HERE = dirname(fileURLToPath(import.meta.url))
const DIST = join(HERE, '..', 'dist')

interface ManifestEntry { css?: string[] }

/**
 * The stylesheet the CLIENT build emitted, located through Vite's own manifest
 * rather than by globbing a hashed filename.
 */
function sheet(): string {
  const manifestPath = join(DIST, '.vite', 'manifest.json')
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as Record<string, ManifestEntry>
  const css = [...new Set(Object.values(manifest).flatMap((e) => e.css ?? []))]
  const only = css[0]
  if (css.length !== 1 || only === undefined) {
    /* One entry, one stylesheet. More than one means the app grew a second CSS
       chunk and the specimen would carry an arbitrary half of the bridge —
       silently, which is the failure shape this repository keeps finding. */
    throw new Error(
      `expected exactly one emitted stylesheet and found ${css.length}: ${JSON.stringify(css)}`,
    )
  }
  return readFileSync(join(DIST, only), 'utf8')
}

/**
 * ⚠️ THE SHEET IS READ ONCE AND SHARED BY BOTH PAGES, WHICH IS THE WHOLE POINT
 * OF `sheet()`'s "exactly one stylesheet" check. Two pages compiled against two
 * builds of the bridge would let the specimen prove a cascade the shell does not
 * have, and the suite's argument — that what is asserted is what SHIPS — would
 * hold for one page and not the other.
 */
const STYLE = sheet()

function page(title: string, source: string, node: ReactElement): string {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<!-- GENERATED by frontend/src/prerender.tsx. Do not edit; edit ${source}.
     Inline rather than linked so the page is self-contained on file://. -->
<style>${STYLE}</style>
</head>
<body>
${renderToStaticMarkup(node)}
</body>
</html>
`
}

function emit(name: string, html: string): void {
  const out = join(DIST, name)
  writeFileSync(out, html)
  process.stdout.write(`prerendered ${out} (${html.length} bytes)\n`)
}

emit('specimen.html', page('Kernel primitives — built specimen', 'Specimen.tsx', <Specimen />))

