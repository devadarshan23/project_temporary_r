/**
 * THE PRERENDER — emits `frontend/dist/specimen.html` and
 * `frontend/dist/shell.html`, the two seams tests/design/ loads over `file://`.
 *
 * 🛑 WHY THE PAGE IS PRE-RENDERED AND FULLY INLINE, WHICH IS NOT A STYLE CHOICE.
 * Chromium blocks `<script type="module">` on a `file://` origin — an ES module
 * fetched from `null` origin fails CORS — so a client-rendered page loaded from
 * disk renders an empty `<div id="root">` and every assertion about a primitive
 * would fail against a page that never mounted. The markup is therefore produced
 * at BUILD time by `react-dom/server`, from the same `<Specimen/>` the dev server
 * renders, and the stylesheet is inlined so the page depends on nothing beside it.
 *
 * ⚠️ AND THE STYLESHEET IS READ, NEVER RE-COMPILED. It is the exact bytes Vite's
 * Tailwind plugin emitted for the app. Compiling `bridge.css` here with the CLI
 * instead would produce an APPROXIMATION of the shipped build — and cascade
 * order, the one property this whole suite is about, is precisely what an
 * approximated build is likeliest to get differently.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import type { ReactElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

import { Shell } from './Shell.tsx'
import { Specimen } from './Specimen.tsx'
import { ChromeBar } from './components/ChromeBar.tsx'
import { HeldCapabilities } from './capabilities.ts'
